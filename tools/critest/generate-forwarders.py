#!/usr/bin/env python3
"""Generate typed pass-through RPCs from the pinned CRI module's protocol."""
import argparse
import hashlib
import re
from pathlib import Path

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--proto", type=Path, required=True)
parser.add_argument("--output", type=Path, required=True)
args = parser.parse_args()
source = args.proto.read_text()
root = Path(__file__).resolve().parents[2]
parts = [(root / ".headers/go.txt").read_text()]
parts += ["\n// Code generated by tools/critest/generate-forwarders.py; DO NOT EDIT.\n",
          f"// API SHA-256: {hashlib.sha256(args.proto.read_bytes()).hexdigest()}\n",
          '\npackage cri\n\nimport (\n"context"\nruntimeapi "k8s.io/cri-api/pkg/apis/runtime/v1"\n)\n']
all_methods = {}
for service, receiver in (("RuntimeService", "runtimeForwarder"), ("ImageService", "imageForwarder")):
    block = re.search(r"service " + service + r"\s*\{(.*?)^\}", source, re.S | re.M)
    if not block:
        raise SystemExit(f"Missing {service} in CRI protocol")
    methods = re.findall(r"rpc\s+(\w+)\s*\(\s*(\w+)\s*\)\s*returns\s*\(\s*(stream\s+)?(\w+)\s*\)", block[1])
    if not methods:
        raise SystemExit(f"No methods found for {service}")
    all_methods[service] = [name for name, *_ in methods]
    for name, request, stream, response in methods:
        if stream:
            parts.append(f"\nfunc (f *{receiver}) {name}(request *runtimeapi.{request}, output runtimeapi.{service}_{name}Server) error {{\n"
                         f"return forwardServerStream(request, output, f.backend.{name})\n}}\n")
        else:
            parts.append(f"\nfunc (f *{receiver}) {name}(ctx context.Context, request *runtimeapi.{request}) (*runtimeapi.{response}, error) {{\n"
                         f"return forwardUnary(ctx, request, f.backend.{name})\n}}\n")
    parts.append(f"\nvar generated{service}Methods = []string{{\n" + "".join(f'"{name}",\n' for name, *_ in methods) + "}\n")
if not {"CheckpointPod", "RestorePod"} <= set(all_methods["RuntimeService"]):
    raise SystemExit("The generator requires a CRI version with whole-Pod RPCs")
args.output.write_text("".join(parts))
